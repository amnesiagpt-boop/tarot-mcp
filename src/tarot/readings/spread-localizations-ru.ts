import type { SpreadType } from "../shared/types.js";
import type { SpreadLocalization } from "./spread-localizations.js";

function spread(
  name: string,
  description: string,
  positions: string,
): SpreadLocalization {
  return {
    name,
    description,
    positions: positions
      .trim()
      .split("\n")
      .map((line) => {
        const [name, meaning] = line.split("|");
        return { name, meaning };
      }),
  };
}

